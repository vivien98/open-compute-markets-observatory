/**
 * Generates one HTML file + one entry module per route.
 *
 * A true multi-page build (rather than an SPA with a 404 fallback) means every
 * URL is a real static file that GitHub Pages serves with a 200, deep links
 * work without JavaScript routing, and each page ships only its own content.
 */
import { readFileSync, writeFileSync, mkdirSync, rmSync } from "node:fs";

const manifest = JSON.parse(readFileSync("app/content/manifest.json", "utf8"));

const routes = [
  { dir: "", entry: "home", title: "Open Compute Markets Observatory", desc: "An evidence-first public dashboard for AI compute supply, bottlenecks, prices, and financing conditions." },
  { dir: "guide", entry: "guide", title: "Field guide · Open Compute Markets", desc: "A structured explainer for every AI compute market, from units and accounting through the open-weight token market up to macro." },
  { dir: "glossary", entry: "glossary", title: "Glossary · Open Compute Markets", desc: "Definitions across compute, silicon, data centers, accounting, finance, macro, strategy, and the token market." },
  { dir: "sources", entry: "sources", title: "Source shelf · Open Compute Markets", desc: "Primary references behind the guide: filings, manufacturer documentation, agency reports, papers." },
  ...manifest.map((m) => ({
    dir: `guide/${m.slug}`,
    entry: `guide-${m.slug}`,
    title: `${m.heading} · Open Compute Markets`,
    desc: m.summary,
  })),
];

const IMPORTS = {
  home: `import Dashboard from "../../app/Dashboard";\nconst Page = Dashboard;`,
  guide: `import GuideIndex from "../../app/site/GuideIndex";\nconst Page = GuideIndex;`,
  glossary: `import GlossaryPage from "../../app/site/GlossaryPage";\nconst Page = GlossaryPage;`,
  sources: `import SourcesPage from "../../app/site/SourcesPage";\nconst Page = SourcesPage;`,
};

rmSync("web/entries", { recursive: true, force: true });
mkdirSync("web/entries", { recursive: true });

for (const route of routes) {
  const body =
    IMPORTS[route.entry] ??
    `import GuidePage from "../../app/site/GuidePage";\n` +
      `import section from "../../app/content/sections/${route.entry.replace(/^guide-/, "")}.json";\n` +
      `const Page = () => <GuidePage section={section as never} />;`;

  writeFileSync(
    `web/entries/${route.entry}.tsx`,
    `// Generated by scripts/build-pages.mjs — do not edit by hand.\n` +
      `import { StrictMode } from "react";\n` +
      `import { createRoot } from "react-dom/client";\n\n` +
      `${body}\n` +
      `import "../../app/globals.css";\n\n` +
      `const container = document.getElementById("root");\n` +
      `if (!container) throw new Error("Root container #root not found");\n` +
      `createRoot(container).render(\n  <StrictMode>\n    <Page />\n  </StrictMode>,\n);\n`,
  );

  const dir = route.dir ? `web/${route.dir}` : "web";
  mkdirSync(dir, { recursive: true });
  writeFileSync(
    `${dir}/index.html`,
    `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <link rel="icon" href="/favicon.svg" />
    <title>${route.title}</title>
    <meta name="description" content="${route.desc.replace(/"/g, "&quot;").trim()}" />
    <meta property="og:title" content="${route.title}" />
    <meta property="og:description" content="${route.desc.replace(/"/g, "&quot;").trim()}" />
    <meta property="og:image" content="/og.png" />
    <meta name="twitter:card" content="summary_large_image" />
  </head>
  <body>
    <div id="root"></div>
    <script type="module" src="/entries/${route.entry}.tsx"></script>
  </body>
</html>
`,
  );
}

writeFileSync("web/routes.json", JSON.stringify(routes.map((r) => r.dir), null, 1));
console.log(`generated ${routes.length} routes`);
for (const r of routes) console.log(`  /${r.dir}`);
